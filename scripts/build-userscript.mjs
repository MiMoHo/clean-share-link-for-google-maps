// Builds dist/clean-share-link-for-google-maps.user.js for Violentmonkey and Tampermonkey
// from manifest.json and src/, so the extension and the userscript never diverge.
// Run: npm run build:userscript
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export const FILE = 'clean-share-link-for-google-maps.user.js';
const ROOT = new URL('../', import.meta.url);
const read = (path) => readFileSync(new URL(path, ROOT), 'utf8');

export function buildUserscript(manifest = JSON.parse(read('manifest.json'))) {
  const repo = manifest.homepage_url;
  const scripts = manifest.content_scripts;
  if (!Array.isArray(scripts) || !scripts.length) throw new Error('manifest.json has no content_scripts');
  const first = scripts[0];
  // A userscript has one match list, one start time and no frame options; refuse anything else.
  for (const cs of scripts) {
    if (cs.matches.join('\n') !== first.matches.join('\n')) throw new Error('content_scripts entries differ in matches');
    if (cs.run_at !== 'document_start') throw new Error('content_scripts must run at document_start');
    for (const key of ['all_frames', 'match_about_blank', 'match_origin_as_fallback', 'exclude_matches', 'include_globs', 'exclude_globs', 'css']) {
      if (cs[key] && (!Array.isArray(cs[key]) || cs[key].length)) throw new Error('content_scripts option not supported by the userscript build: ' + key);
    }
  }
  // MAIN-world files first, so the share and clipboard wrappers exist before the rest runs.
  const files = [...scripts.filter((cs) => cs.world === 'MAIN'), ...scripts.filter((cs) => cs.world !== 'MAIN')].flatMap((cs) => cs.js);
  for (const path of files) {
    if (/[\r\n\u2028\u2029]/.test(path)) throw new Error('content script path must be a single line');
  }
  const icon = 'data:image/svg+xml;base64,' + Buffer.from(read(Object.values(manifest.icons)[0])).toString('base64');
  const download = `${repo}/releases/latest/download/${FILE}`;
  const meta = [
    ['name', manifest.name],
    ['namespace', repo],
    ['version', manifest.version],
    ['description', manifest.description],
    ['homepageURL', repo],
    ['supportURL', repo + '/issues'],
    ['downloadURL', download],
    ['updateURL', download],
    ['icon', icon],
    ['license', 'MIT'],
    ...first.matches.map((m) => ['match', m]),
    ['run-at', 'document-start'],
    ['inject-into', 'page'],
    ['grant', 'none'],
    ['noframes', ''],
  ];
  // JavaScript also ends a line comment at U+2028/U+2029; a value must neither break the
  // comment nor close the metadata block.
  for (const [key, value] of meta) {
    if (/[\r\n\u2028\u2029]/.test(value)) throw new Error('metadata value must be a single line: @' + key);
    if (/==\/?UserScript==/i.test(value)) throw new Error('metadata value must not contain a block marker: @' + key);
  }
  const width = Math.max(...meta.map(([k]) => k.length)) + 2;
  const header = meta.map(([k, v]) => ('// @' + k.padEnd(width) + v).trimEnd()).join('\n');

  // Hinweis: the extension runs page.js in the page's world and core.js/content.js in an
  // isolated world. A userscript has one world, so all three share a function scope here.
  // The local, prototype-free `globalThis` and `module` keep NTMapsCore off the page's window
  // and stop page-defined globals or Object.prototype properties from changing the flow.
  // content.js writes the clipboard through the page.js wrapper; copy() publishes the
  // copied link on <html> first, so the wrapper swaps it for the identical value.
  const body = files
    .map((path) => `// ---- ${path} ----\n${read(path).trimEnd()}`)
    .join('\n\n');
  return `// ==UserScript==\n${header}\n// ==/UserScript==\n\n// Generated by scripts/build-userscript.mjs from ${repo}; edit src/ instead.\n(function () {\n  'use strict';\n  const globalThis = Object.create(null);\n  const module = undefined;\n\n${body}\n})();\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  mkdirSync(new URL('dist/', ROOT), { recursive: true });
  const out = new URL('dist/' + FILE, ROOT);
  writeFileSync(out, buildUserscript());
  console.log('Userscript ready:', 'dist/' + FILE);
}
